const startTime = new Date("2024-02-15T00:00:00.000Z");
const endTime = new Date("2024-02-15T23:59:59.999Z");

// 設定初始時間
let currentTime = new Date(startTime);

// 定義插入資料的函式
function insertData() {
  // 更新 Document 的時間
  Document.time = currentTime;

  // 插入資料到 CouchDB
  nanoDb
    .insert(Document)
    .then((body) => {
      console.log("User document inserted successfully. ID:", body.id);
    })
    .catch((err) => {
      console.error("Error inserting user document:", err.message);
    });

  // 將時間增加一秒
  currentTime.setSeconds(currentTime.getSeconds() + 1);

  // 如果時間仍在範圍內，繼續插入資料
  if (currentTime <= endTime) {
    // 每秒執行一次 insertData 函式
    setTimeout(insertData, 10);
  }
}

