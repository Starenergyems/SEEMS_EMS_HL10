function generateRandomCouchDbId() {
  const chars = abcdefghijklmnopqrstuvwxyz0123456789;
  const idLength = 32;
  let id = "";

  for (let i = 0; i < idLength; i++) {
    const randomIndex = Math.floor(Math.random() * chars.length);
    id += chars.charAt(randomIndex);
  }

  return id;
}

